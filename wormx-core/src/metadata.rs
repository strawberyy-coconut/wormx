//! Runtime table, column, and relation metadata.

use std::fmt;

/// A schema-qualified table name.
#[derive(Debug, Clone, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub struct TableRef {
    pub schema: Option<String>,
    pub name: String,
}

impl TableRef {
    pub fn new(name: impl Into<String>) -> Self {
        Self {
            schema: None,
            name: name.into(),
        }
    }

    /// Parses `table` or `schema.table`.
    ///
    /// A dot inside double quotes, backticks, or brackets does not split the name.
    pub fn parse(input: &str) -> Result<Self, TableRefError> {
        let input = input.trim();
        if input.is_empty() {
            return Err(TableRefError::Empty);
        }

        let mut quote: Option<char> = None;
        let mut split_at = None;

        for (index, ch) in input.char_indices() {
            match quote {
                Some('"') if ch == '"' => quote = None,
                Some('`') if ch == '`' => quote = None,
                Some(']') if ch == ']' => quote = None,
                Some(_) => {}
                None => match ch {
                    '"' | '`' => quote = Some(ch),
                    '[' => quote = Some(']'),
                    '.' => {
                        split_at = Some(index);
                        break;
                    }
                    _ => {}
                },
            }
        }

        let (schema, name) = match split_at {
            Some(index) => (&input[..index], &input[index + 1..]),
            None => ("", input),
        };

        let name = unquote_identifier(name)?;
        if name.is_empty() {
            return Err(TableRefError::Empty);
        }

        let schema = if schema.is_empty() {
            None
        } else {
            Some(unquote_identifier(schema)?)
        };

        Ok(Self { schema, name })
    }

    pub fn qualified_name(&self) -> String {
        match &self.schema {
            Some(schema) => format!("{schema}.{}", self.name),
            None => self.name.clone(),
        }
    }
}

impl fmt::Display for TableRef {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.qualified_name())
    }
}

fn unquote_identifier(input: &str) -> Result<String, TableRefError> {
    let input = input.trim();
    if input.is_empty() {
        return Err(TableRefError::Empty);
    }

    if input.len() >= 2 {
        let first = input.chars().next().unwrap();
        let last = input.chars().last().unwrap();
        match (first, last) {
            ('"', '"') => {
                return Ok(input[1..input.len() - 1].replace("\"\"", "\""));
            }
            ('`', '`') => {
                return Ok(input[1..input.len() - 1].replace("``", "`"));
            }
            ('[', ']') => {
                return Ok(input[1..input.len() - 1].replace("]]", "]"));
            }
            _ => {}
        }
    }

    if input.contains('"') || input.contains('`') || input.contains('[') || input.contains(']') {
        return Err(TableRefError::Invalid(input.to_owned()));
    }

    Ok(input.to_owned())
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
/// Errors from parsing a table reference.
pub enum TableRefError {
    #[error("table name must not be empty")]
    Empty,
    #[error("invalid table name {0:?}")]
    Invalid(String),
}

/// Runtime metadata for one column.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ColumnDef {
    /// The SQL column name.
    pub name: &'static str,
    /// The SQL type name reported by the driver.
    pub sql_type: &'static str,
    /// Whether the column accepts `NULL`.
    pub nullable: bool,
    /// Whether the column participates in the primary key.
    pub primary_key: bool,
    /// Whether the column has a database default.
    pub has_default: bool,
    /// Whether the column is an identity/auto-increment column.
    pub identity: bool,
    /// Whether the column is generated by the database.
    pub generated: bool,
}

/// The direction of a generated relation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RelationKind {
    /// A relation from a foreign key on this table to the referenced row.
    BelongsTo,
    /// A relation from this row's key to rows whose foreign key points here.
    HasMany,
}

/// Runtime metadata for one relation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RelationDef {
    /// The generated Rust field name.
    pub name: &'static str,
    /// The relation direction.
    pub kind: RelationKind,
    /// The referenced table name.
    pub target_table: &'static str,
    /// The referenced table schema.
    pub target_schema: Option<&'static str>,
    /// The columns on this table that form the relation key.
    pub source_columns: &'static [&'static str],
    /// The matching columns on the target table.
    pub target_columns: &'static [&'static str],
}

/// Runtime metadata for one table.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TableDef {
    /// The SQL table name.
    pub name: &'static str,
    /// The SQL schema name.
    pub schema: Option<&'static str>,
    /// The table's columns.
    pub columns: &'static [ColumnDef],
    /// The primary-key columns in key order.
    pub primary_key: &'static [&'static str],
    /// Relations generated from foreign keys.
    pub relations: &'static [RelationDef],
}

impl TableDef {
    pub fn qualified_name(&self) -> String {
        match self.schema {
            Some(schema) => format!("{schema}.{}", self.name),
            None => self.name.to_owned(),
        }
    }
}

/// Implemented by structs generated by `wormx::table!`.
pub trait Table {
    const DEF: &'static TableDef;
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_and_unescapes_quoted_identifiers() {
        assert_eq!(
            TableRef::parse("\"public\".\"user\"\"names\""),
            Ok(TableRef {
                schema: Some("public".to_owned()),
                name: "user\"names".to_owned(),
            })
        );
        assert_eq!(
            TableRef::parse("`app`.`tick``tock`"),
            Ok(TableRef {
                schema: Some("app".to_owned()),
                name: "tick`tock".to_owned(),
            })
        );
        assert_eq!(
            TableRef::parse("[dbo].[brack]]et]"),
            Ok(TableRef {
                schema: Some("dbo".to_owned()),
                name: "brack]et".to_owned(),
            })
        );
    }
}
