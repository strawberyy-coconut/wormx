use std::fmt;

/// A schema-qualified table name.
#[derive(Debug, Clone, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub struct TableRef {
    pub schema: Option<String>,
    pub name: String,
}

impl TableRef {
    pub fn new(name: impl Into<String>) -> Self {
        Self {
            schema: None,
            name: name.into(),
        }
    }

    /// Parses `table` or `schema.table`.
    ///
    /// A dot inside double quotes, backticks, or brackets does not split the name.
    pub fn parse(input: &str) -> Result<Self, TableRefError> {
        let input = input.trim();
        if input.is_empty() {
            return Err(TableRefError::Empty);
        }

        let mut quote: Option<char> = None;
        let mut split_at = None;

        for (index, ch) in input.char_indices() {
            match quote {
                Some('"') if ch == '"' => quote = None,
                Some('`') if ch == '`' => quote = None,
                Some(']') if ch == ']' => quote = None,
                Some(_) => {}
                None => match ch {
                    '"' | '`' => quote = Some(ch),
                    '[' => quote = Some(']'),
                    '.' => {
                        split_at = Some(index);
                        break;
                    }
                    _ => {}
                },
            }
        }

        let (schema, name) = match split_at {
            Some(index) => (&input[..index], &input[index + 1..]),
            None => ("", input),
        };

        let name = unquote_identifier(name)?;
        if name.is_empty() {
            return Err(TableRefError::Empty);
        }

        let schema = if schema.is_empty() {
            None
        } else {
            Some(unquote_identifier(schema)?)
        };

        Ok(Self { schema, name })
    }

    pub fn qualified_name(&self) -> String {
        match &self.schema {
            Some(schema) => format!("{schema}.{}", self.name),
            None => self.name.clone(),
        }
    }
}

impl fmt::Display for TableRef {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.qualified_name())
    }
}

fn unquote_identifier(input: &str) -> Result<String, TableRefError> {
    let input = input.trim();
    if input.is_empty() {
        return Err(TableRefError::Empty);
    }

    if input.len() >= 2 {
        let first = input.chars().next().unwrap();
        let last = input.chars().last().unwrap();
        match (first, last) {
            ('"', '"') | ('`', '`') | ('[', ']') => {
                return Ok(input[1..input.len() - 1].to_owned());
            }
            _ => {}
        }
    }

    if input.contains('"') || input.contains('`') || input.contains('[') || input.contains(']') {
        return Err(TableRefError::Invalid(input.to_owned()));
    }

    Ok(input.to_owned())
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum TableRefError {
    #[error("table name must not be empty")]
    Empty,
    #[error("invalid table name {0:?}")]
    Invalid(String),
}

/// Runtime metadata for one column.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ColumnDef {
    pub name: &'static str,
    pub sql_type: &'static str,
    pub nullable: bool,
    pub primary_key: bool,
    pub has_default: bool,
    pub identity: bool,
    pub generated: bool,
}

/// The direction of a generated relation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RelationKind {
    BelongsTo,
    HasMany,
}

/// Runtime metadata for one relation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RelationDef {
    pub name: &'static str,
    pub kind: RelationKind,
    pub target_table: &'static str,
    pub target_schema: Option<&'static str>,
    pub source_columns: &'static [&'static str],
    pub target_columns: &'static [&'static str],
}

/// Runtime metadata for one table.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TableDef {
    pub name: &'static str,
    pub schema: Option<&'static str>,
    pub columns: &'static [ColumnDef],
    pub primary_key: &'static [&'static str],
    pub relations: &'static [RelationDef],
}

impl TableDef {
    pub fn qualified_name(&self) -> String {
        match self.schema {
            Some(schema) => format!("{schema}.{}", self.name),
            None => self.name.to_owned(),
        }
    }
}

/// Implemented by structs generated by `wormx::table!`.
pub trait Table {
    const DEF: &'static TableDef;
}
